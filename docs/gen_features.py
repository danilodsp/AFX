"""Write docs/features.md from afx_audio.feature_info. Run after changing an extractor."""
import os
import sys

# Document the checkout this script sits in, not whichever afx_audio is installed
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import afx_audio  # noqa: E402
from afx_audio.registry import GROUPS  # noqa: E402

HEADER = """# Feature reference

Generated by `docs/gen_features.py` from the extractor signatures and
docstrings. Every feature is called as `afx_audio.FEATURE_MAP[name](signal, sr,
**parameters)` and returns `{name: array}`; "rows" is the size of the first
axis of that array (1 means one value per frame, shape `(n_frames,)`).
"""


def render() -> str:
    lines = [HEADER]
    for group in GROUPS:
        names = afx_audio.list_features(group)
        if not names:
            continue
        lines.append(f'\n## {group.capitalize()}\n')
        for name in names:
            info = afx_audio.feature_info(name)
            lines.append(f'### `{name}`\n')
            lines.append(f"{info['summary']}\n")
            lines.append(f"Units: {info['units']}. Rows: {info['rows']}. Function: `{info['function']}`.\n")
            params = ', '.join(f'`{k}={v!r}`' for k, v in info['parameters'].items()) or 'none'
            lines.append(f'Parameters: {params}.\n')
    return '\n'.join(lines)


if __name__ == '__main__':
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'features.md')
    text = render()
    if '--check' in sys.argv:
        with open(path, encoding='utf-8') as f:
            sys.exit(0 if f.read() == text else 1)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
